#!/usr/bin/env node
// Pin and vendor the complete PixelFX catalog. No network access at game runtime.
// Usage: node bin/import-pixelfx.mjs /path/to/patch-gg/pixelfx
import {readdirSync, mkdirSync, readFileSync, writeFileSync, copyFileSync} from 'node:fs';
import {resolve, join, dirname} from 'node:path';
import {pathToFileURL, fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const source = resolve(process.argv[2]), root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'client/js/lib/pixelfx');
function copy(dir, relative = '') {
    for (const entry of readdirSync(dir, {withFileTypes:true})) {
        const name = join(relative, entry.name), from = join(dir, entry.name);
        if (entry.isDirectory()) copy(from, name);
        else if (entry.name.endsWith('.js')) {
            const out = join(target, name.replace(/\.js$/, '.mjs')); mkdirSync(dirname(out), {recursive:true});
            writeFileSync(out, readFileSync(from, 'utf8').replace(/((?:from\s*|import\s*)["'][^"']+)\.js(["'])/g, '$1.mjs$2'));
        }
    }
}
copy(join(source, 'src'));
const {allIds, loadEffect} = await import(pathToFileURL(join(source, 'tools/lib/fxlib.mjs')));
const {PAL: palettes} = await import(pathToFileURL(join(source, 'src/core/color.js')));
const effects = {};
for (const id of allIds()) {
    const {meta} = await loadEffect(id);
    const options=Object.fromEntries(Object.entries(meta.options || {}).filter(([key])=>!['seed','palette'].includes(key)));
    effects[id] = {name:meta.name, category:id.split('/')[0], size:meta.size, origin:meta.origin, duration:Math.round(meta.duration*1000), loop:meta.loop, actor:!!meta.actor, options};
}
const revision = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim();
writeFileSync(join(root, 'shared/js/pixelfxcatalog.js'), '// Generated by bin/import-pixelfx.mjs; upstream '+revision+'\n(function(root,factory){if(typeof module==="object"&&module.exports)module.exports=factory();else if(typeof define==="function"&&define.amd)define([],factory);else root.PixelFxCatalog=factory();})(typeof globalThis!=="undefined"?globalThis:this,function(){return '+JSON.stringify({revision,effects,palettes})+';});\n');
for (const file of ['LICENSE', 'NOTICE.md']) copyFileSync(join(source,file),join(target,file));
writeFileSync(join(target,'README.md'), '# PixelFX\n\nVendored from https://github.com/patch-gg/pixelfx at `'+revision+'`.\nMIT licensed; see LICENSE and NOTICE.md. Imports and extensions converted to .mjs for native modules.\nRegenerate with `node bin/import-pixelfx.mjs <upstream-checkout>`.\n');
console.log(Object.keys(effects).length+' effects imported.');
